# -*- coding: utf-8 -*-
"""Vantage i18n 资源生成器。

唯一数据源是同目录的 l10n_master.py：
    MASTER = { "semantic.key": ("简体中文", "English"), ... }
    PHRASES = { "中文运行时短语": "English", ... }

生成：
    Resources/zh-Hans.lproj/Localizable.strings   "key" = "中文";
    Resources/en.lproj/Localizable.strings        "key" = "English";
    Sources/Vantage/L10nTable.swift               内嵌 zh / en / phrases（fallback）
    Sources/Vantage/L10nKeys.swift                L10nKey 常量（强类型入口）

从任意工作目录运行：python3 Tools/build_l10n.py
中文**不再是 key**：源码里只写 L("semantic.key")，中文是 zh 表里的 value。
"""
import re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from l10n_master import MASTER, PHRASES   # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'Resources'
SW = ROOT / 'Sources' / 'Vantage'

ZH = re.compile(r'[\u4e00-\u9fff]')

def esc(s: str) -> str:
    return (s.replace('\\', '\\\\').replace('"', '\\"')
             .replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r'))

def swift(s: str) -> str:
    return '"' + esc(s) + '"'

# ---------------------------------------------------------------- 校验
errors = []
for k, (zh, en) in MASTER.items():
    if not re.fullmatch(r'[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9_]+)+', k):
        errors.append(f'非法 key 格式: {k}')
    if ZH.search(en):
        errors.append(f'英文仍含中文: {k} -> {en[:60]!r}')
    # 占位符 {0} {1} 在两种语言里编号必须一致
    a = sorted(set(re.findall(r'\{(\d+)\}', zh)))
    b = sorted(set(re.findall(r'\{(\d+)\}', en)))
    if a != b:
        errors.append(f'占位符不一致: {k} zh={a} en={b}')
if errors:
    print('!! 主表校验失败:')
    for e in errors[:30]: print('   ', e)
    raise SystemExit(1)

# 源码里出现的 key 全都必须在主表里（Localization/L10nKeys/L10nTable 除外）
src_keys = set()
for p in SW.glob('*.swift'):
    if p.name in ('Localization.swift', 'L10nTable.swift', 'L10nKeys.swift'):
        continue
    src_keys.update(re.findall(r'\bL\(\s*"([a-zA-Z0-9_.]+)"', p.read_text()))
missing = sorted(src_keys - set(MASTER))
if missing:
    print('!! 源码引用了主表里没有的 key:')
    for k in missing[:30]: print('   ', k)
    raise SystemExit(1)

print(f'主表 {len(MASTER)} 条 | 源码引用 {len(src_keys)} 个 key | '
      f'运行时短语 {len(PHRASES)} 条 | 校验通过')

# ---------------------------------------------------------------- .strings
(RES / 'zh-Hans.lproj').mkdir(parents=True, exist_ok=True)
(RES / 'en.lproj').mkdir(parents=True, exist_ok=True)

header = ('/* SPDX-License-Identifier: MIT */\n'
          '/* Vantage localization — generated by Tools/build_l10n.py\n'
          '   Edit Tools/l10n_master.py instead of this file.\n'
          '   Keys are semantic identifiers; Chinese is a VALUE, never a key. */\n\n')
for lang, idx in (('zh-Hans', 0), ('en', 1)):
    lines = [header]
    for k in sorted(MASTER):
        lines.append(f'"{esc(k)}" = "{esc(MASTER[k][idx])}";\n')
    (RES / f'{lang}.lproj' / 'Localizable.strings').write_text(
        ''.join(lines), encoding='utf-8')

# ---------------------------------------------------------------- L10nTable.swift
t_zh = '\n'.join(f'        {swift(k)}: {swift(v[0])},' for k, v in sorted(MASTER.items()))
t_en = '\n'.join(f'        {swift(k)}: {swift(v[1])},' for k, v in sorted(MASTER.items()))
t_ph = '\n'.join(f'        ({swift(k)}, {swift(v)}),' for k, v in sorted(PHRASES.items()))
table = f'''// SPDX-License-Identifier: MIT
import Foundation

// 由 Tools/build_l10n.py 从 l10n_master.py 生成，请勿手工编辑。
// 内嵌表是 Bundle 里 .lproj 资源不可用时的兜底（swift run / 手工 .app）。
// 注意：中文在这里是 **value**，不是 key。
enum L10nTable {{
    static let zh: [String: String] = [
{t_zh}
    ]

    static let en: [String: String] = [
{t_en}
    ]

    /// C 层运行时拼接文本的中文短语 → 英文，按长度降序先替换长句。
    /// C 层输出是 \t 分隔的纯文本、格式串里混着变量，无法给它分配 key，
    /// 只能做字段级文本映射；UI 字符串本身 100% 走语义 key。
    static let phrases: [(String, String)] = [
{t_ph}
    ].sorted {{ $0.0.count > $1.0.count }}

    /// 完整匹配优先：C 层固定说明行（phrases 里恰好等于整字段的条目）
    static let phraseExact: [String: String] = {{
        var d: [String: String] = [:]
        for (k, v) in phrases {{ d[k] = v }}
        return d
    }}()

    static func hasChinese(_ s: String) -> Bool {{
        s.unicodeScalars.contains {{ $0.value >= 0x4e00 && $0.value <= 0x9fff }}
    }}
}}
'''
(SW / 'L10nTable.swift').write_text(table, encoding='utf-8')

# ---------------------------------------------------------------- L10nKeys.swift
def const_name(key: str) -> str:
    parts = key.split('.')
    return parts[0] + ''.join(p[:1].upper() + p[1:].replace('_', '') for p in parts[1:])

used = set()
keys_lines = []
for k in sorted(MASTER):
    name = const_name(k)
    base, i = name, 2
    while name in used:
        name = f'{base}{i}'; i += 1
    used.add(name)
    keys_lines.append(f'    static let {name} = "{k}"')
keys_src = ('''// SPDX-License-Identifier: MIT
import Foundation

// 由 Tools/build_l10n.py 生成：语义 key 的强类型常量入口。
// 源码可以直接写 L("detail.cmd.header")，也可以写 L(L10nKey.detailCmdHeader)；
// 两者等价，后者便于 IDE 补全与重命名。新增文案请改 l10n_master.py 后重新生成。
enum L10nKey {
''' + '\n'.join(keys_lines) + '\n}\n')
(SW / 'L10nKeys.swift').write_text(keys_src, encoding='utf-8')

print('✓ zh-Hans.lproj / en.lproj / L10nTable.swift / L10nKeys.swift')

# C 层运行时文本的双语表也一起生成（共用 l10n_master.py 的现有译文 +
# c_en_override.py 的手工译文），保证改文案后一次跑完不会漏。
import subprocess
subprocess.run([sys.executable, str(Path(__file__).resolve().parent / 'build_c_l10n.py')],
               check=True)
